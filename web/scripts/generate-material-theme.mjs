import { writeFile } from 'node:fs/promises';
import { Hct, SchemeTonalSpot, argbFromHex, hexFromArgb } from '@material/material-color-utilities';

// Google MCU owns the tone/contrast relationships. Do not hand-tune role pairs.
const seed = '#456b55';
const roles = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer', 'surface', 'onSurface',
  'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow',
  'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'onSurfaceVariant', 'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface',
  'inversePrimary', 'shadow', 'scrim'];
const kebab = value => value.replace(/[A-Z]/g, char => `-${char.toLowerCase()}`);
let css = `/* Generated by web/scripts/generate-material-theme.mjs. Google MCU 0.3.0; seed ${seed}. */\n`;
for (const dark of [false, true]) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  css += `${dark ? '.theme-dark' : ':root, .theme-light'} {\n`;
  for (const role of roles) css += `  --md-sys-color-${kebab(role)}: ${hexFromArgb(scheme[role])};\n`;
  css += '}\n';
}
await writeFile(new URL('../src/styles/material-tokens.css', import.meta.url), css);
